"""Turns ElevenLabs word timings (scripts/words.json) into src/thinkbig/vo.ts.

The narration is cut into sentence segments; each is re-placed on the output
timeline with a chosen gap before it, which stretches the 70.6 s read to ~90 s
and leaves room for visual beats between scenes.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
words = json.load(open(ROOT / "scripts/words.json"))

# (first word index start time in source, last word end time in source, gap before [s], scene id of first segment or None)
SEGS = [
    (0.00, 6.69, 0.9, 1),
    (7.29, 14.00, 2.6, 2),
    (14.44, 18.80, 0.6, None),
    (19.49, 21.61, 2.5, 3),
    (21.93, 24.39, 0.35, None),
    (24.83, 29.52, 0.6, None),
    (30.13, 32.07, 2.4, 4),
    (32.34, 37.24, 0.45, None),
    (37.85, 40.82, 2.8, 5),
    (41.20, 46.27, 0.8, None),
    (46.71, 48.02, 2.8, 6),
    (48.26, 49.40, 0.45, None),
    (49.68, 51.61, 0.65, None),
    (51.93, 53.91, 0.65, None),
    (54.23, 57.38, 0.65, None),
    (57.82, 60.23, 2.8, 7),
    (60.51, 64.55, 0.45, None),
    (65.16, 67.25, 0.9, None),
    (67.76, 70.54, 0.45, None),
]
PRE, POST = 0.05, 0.16  # audio padding around each segment (inside the natural pauses)
END_HOLD = 3.5
SCENE_LEAD = 0.75  # scene starts this long before its first narration line

out_segs, out_words, scenes = [], [], {}
t = 0.0
prev_end_out = 0.0
for i, (s, e, gap, scene) in enumerate(SEGS):
    at = prev_end_out + gap
    if scene:
        scenes[scene] = 0.0 if scene == 1 else round(at - SCENE_LEAD, 3)
    src_from = max(0.0, s - PRE)
    src_to = e + POST
    out_segs.append({"srcFrom": round(src_from, 3), "srcTo": round(src_to, 3), "at": round(at - (s - src_from), 3)})
    for w in words:
        if w["s"] >= s - 0.01 and w["e"] <= e + 0.01:
            out_words.append({"w": w["w"], "s": round(at + w["s"] - s, 3), "e": round(at + w["e"] - s, 3)})
    prev_end_out = at + (e - s)

duration = prev_end_out + END_HOLD
ts = f"""// GENERATED by scripts/build_vo_timeline.py — do not edit by hand.
export const VO_SEGMENTS = {json.dumps(out_segs, indent=1)};
export const WORDS: {{ w: string; s: number; e: number }}[] = {json.dumps(out_words)};
export const SCENE_STARTS: number[] = {json.dumps([scenes[k] for k in sorted(scenes)])};
export const DURATION_S = {round(duration, 3)};
"""
(ROOT / "src/thinkbig/vo.ts").write_text(ts)
print("duration", round(duration, 2), "scenes", scenes)
